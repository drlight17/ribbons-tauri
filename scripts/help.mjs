import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;

console.log(`
Ribbons Screensaver ${version} — Tauri build helper

Development:
  npm install
  npm run dev

Production bundles:
  npm run build              # platform default bundles
  npm run build-deb          # Debian/Ubuntu (update-blocked)
  npm run build-rpm          # Fedora/RHEL (update-blocked)
  npm run build-AppImage     # portable Linux AppImage (not update-blocked)
  npm run build-targz        # raw binary tar.gz
  npm run build-exe          # Windows NSIS installer
  npm run build-msi          # Windows MSI
  npm run build-zip          # Windows portable zip
  npm run build-dmg          # macOS DMG, host arch (not update-blocked)
  npm run build-zip-mac      # macOS .app zip
  npm run build-linux        # all Linux formats
  npm run build-win          # zip + msi + nsis
  npm run build-mac          # x86_64 + arm64 dmg/zip/updater
  npm run build-mac -- --universal   # one universal build

Update blocking:
  npm run block              # creates UPDATE_BLOCK before a build
  npm run unblock            # removes it again
  (deb and rpm builds are update-blocked; dmg is not)

Linux system packages (Arch/CachyOS):
  sudo pacman -S --needed base-devel webkit2gtk-4.1 libayatana-appindicator \
    gtk3 libsoup3 openssl wget file

Debian/Ubuntu:
  sudo apt install build-essential curl wget file libssl-dev \
    libwebkit2gtk-4.1-dev libayatana-appindicator3-dev librsvg2-dev

Runtime helpers:
  Linux fullscreen detection uses wctx on Wayland and xprop on X11.
  Screen lock/suspend uses the freedesktop DBus interfaces.
  System audio detection uses parec on Linux and WASAPI/CoreAudio loopback
  through CPAL on Windows/macOS.

Config:
  Linux:   ~/.config/Ribbons Screensaver/config.json
  macOS:   ~/Library/Application Support/Ribbons Screensaver/config.json
  Windows: %AppData%\\Ribbons Screensaver\\config.json
  Dev builds use the "-dev" suffix.

Tauri updater:
  Set TAURI_SIGNING_PRIVATE_KEY and replace plugins.updater.pubkey in
  src-tauri/tauri.conf.json with the matching public key generated by
  \`npx @tauri-apps/cli signer generate\`. Publish latest.json with releases.
  The build scripts additionally write latest-linux.json, latest-win.json and
  latest-mac.json listing every signed bundle and the updater platforms for
  that OS. Merge them before publishing:
  npm run merge-latest      # writes the combined latest.json
`);
